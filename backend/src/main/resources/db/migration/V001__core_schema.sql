CREATE TABLE local_patient_record_overlays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id bigint NOT NULL REFERENCES patients(source_id) ON DELETE CASCADE,
  category varchar(64) NOT NULL,
  record_id varchar(255) NOT NULL,
  operation varchar(16) NOT NULL CHECK (operation IN ('upsert', 'delete')),
  source_ordinal integer NOT NULL DEFAULT 0 CHECK (source_ordinal >= 0),
  payload jsonb,
  payload_sha256 char(64),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_local_patient_record UNIQUE (patient_id, category, record_id),
  CONSTRAINT chk_local_patient_record_payload CHECK (
    (operation = 'delete' AND payload IS NULL AND payload_sha256 IS NULL) OR
    (operation = 'upsert' AND payload IS NOT NULL AND payload_sha256 IS NOT NULL)
  )
);

CREATE TABLE local_reference_record_overlays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category varchar(64) NOT NULL,
  record_id varchar(255) NOT NULL,
  operation varchar(16) NOT NULL CHECK (operation IN ('upsert', 'delete')),
  source_ordinal integer NOT NULL DEFAULT 0 CHECK (source_ordinal >= 0),
  payload jsonb,
  payload_sha256 char(64),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_local_reference_record UNIQUE (category, record_id)
);

CREATE TABLE clinical_treatments (
  id varchar(255) PRIMARY KEY,
  patient_id bigint NOT NULL REFERENCES patients(source_id) ON DELETE RESTRICT,
  diagnosis_id varchar(255),
  created_on date NOT NULL,
  first_cycle_date date,
  initial_cycle smallint NOT NULL DEFAULT 1 CHECK (initial_cycle BETWEEN 1 AND 500),
  cycle_count smallint NOT NULL DEFAULT 1 CHECK (cycle_count BETWEEN 1 AND 500),
  cycle_days smallint CHECK (cycle_days BETWEEN 0 AND 3650),
  treatment_type varchar(255),
  intent varchar(255),
  diagnosis varchar(2000),
  scheme_id varchar(255),
  scheme_name varchar(1000) NOT NULL,
  oncologist varchar(500),
  treatment_status varchar(96) NOT NULL DEFAULT 'Registrado',
  consent_status varchar(96),
  consent_available boolean NOT NULL DEFAULT false,
  estimated_duration_minutes smallint CHECK (estimated_duration_minutes BETWEEN 1 AND 1440),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_by bigint NOT NULL REFERENCES local_users(id),
  updated_by bigint NOT NULL REFERENCES local_users(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX idx_clinical_treatments_patient ON clinical_treatments (patient_id, created_on DESC);

CREATE TABLE treatment_details (
  treatment_id varchar(255) PRIMARY KEY REFERENCES clinical_treatments(id) ON DELETE CASCADE,
  detail_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  updated_by bigint NOT NULL REFERENCES local_users(id),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE unified_infusion_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id bigint NOT NULL REFERENCES patients(source_id) ON DELETE RESTRICT,
  treatment_id varchar(255) NOT NULL REFERENCES clinical_treatments(id) ON DELETE RESTRICT,
  cycle_number smallint NOT NULL CHECK (cycle_number BETWEEN 1 AND 500),
  application_id bigint,
  scheduled_at timestamptz,
  chair varchar(128),
  duration_minutes smallint CHECK (duration_minutes BETWEEN 1 AND 1440),
  clinical_status varchar(32) NOT NULL DEFAULT 'planned'
    CHECK (clinical_status IN ('planned','checked_in','ready','in_progress','observation','paused','completed','cancelled')),
  pharmacy_status varchar(32) NOT NULL DEFAULT 'pending'
    CHECK (pharmacy_status IN ('not_required','pending','in_preparation','ready','released','cancelled')),
  administration_status varchar(32) NOT NULL DEFAULT 'not_started'
    CHECK (administration_status IN ('not_started','in_progress','completed','withheld','cancelled')),
  appointment_confirmed boolean NOT NULL DEFAULT false,
  notes text,
  source_ref jsonb NOT NULL DEFAULT '{}'::jsonb,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_by bigint NOT NULL REFERENCES local_users(id),
  updated_by bigint NOT NULL REFERENCES local_users(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX idx_unified_infusion_schedule ON unified_infusion_sessions (scheduled_at, clinical_status);
CREATE INDEX idx_unified_infusion_patient ON unified_infusion_sessions (patient_id, updated_at DESC);
CREATE INDEX idx_unified_infusion_treatment ON unified_infusion_sessions (treatment_id, cycle_number);
CREATE UNIQUE INDEX uq_unified_infusion_active_slot
  ON unified_infusion_sessions (patient_id, treatment_id, cycle_number, scheduled_at)
  WHERE clinical_status <> 'cancelled';

