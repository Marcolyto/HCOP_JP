CREATE TABLE treatment_workflow_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_type varchar(32) NOT NULL CHECK (request_type IN ('prescription_request','continuity_request')),
  status varchar(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','resolved','cancelled')),
  patient_id bigint NOT NULL REFERENCES patients(source_id) ON DELETE RESTRICT,
  treatment_id varchar(255) NOT NULL REFERENCES clinical_treatments(id) ON DELETE RESTRICT,
  cycle_number smallint NOT NULL CHECK (cycle_number BETWEEN 1 AND 500),
  requested_by_user_id bigint NOT NULL REFERENCES local_users(id),
  assigned_to_user_id bigint NOT NULL REFERENCES local_users(id),
  message varchar(3000),
  context_json jsonb NOT NULL,
  resolution varchar(32)
    CHECK (resolution IN ('prescription_confirmed','prescription_rejected','continue','temporary_hold','discontinued')),
  resolution_reason varchar(3000),
  resume_date date,
  seen_at timestamptz,
  resolved_at timestamptz,
  resolved_by_user_id bigint REFERENCES local_users(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX idx_treatment_workflow_inbox
  ON treatment_workflow_requests (assigned_to_user_id, status, created_at DESC);
CREATE UNIQUE INDEX uq_treatment_workflow_pending
  ON treatment_workflow_requests (patient_id, treatment_id, cycle_number, request_type)
  WHERE status = 'pending';

CREATE TABLE clinical_workflow_events (
