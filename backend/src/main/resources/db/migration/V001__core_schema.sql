CREATE TABLE local_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(96) NOT NULL,
  email varchar(320) NOT NULL,
  password_hash varchar(512) NOT NULL,
  display_name varchar(255),
  specialty varchar(255),
  license_number varchar(128),
  enabled boolean NOT NULL DEFAULT true,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_local_users_username UNIQUE (username),
  CONSTRAINT uq_local_users_email UNIQUE (email)
);

CREATE TABLE local_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_key varchar(128) NOT NULL UNIQUE,
  display_name varchar(255) NOT NULL,
  description varchar(1000),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE local_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_key varchar(96) NOT NULL UNIQUE,
  display_name varchar(255) NOT NULL,
  description varchar(1000),
  system_role boolean NOT NULL DEFAULT false,
  enabled boolean NOT NULL DEFAULT true,
  created_by bigint REFERENCES local_users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES local_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE local_role_permissions (
  role_id bigint NOT NULL REFERENCES local_roles(id) ON DELETE CASCADE,
  permission_id bigint NOT NULL REFERENCES local_permissions(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE local_user_roles (
  user_id bigint NOT NULL REFERENCES local_users(id) ON DELETE CASCADE,
  role_id bigint NOT NULL REFERENCES local_roles(id) ON DELETE CASCADE,
  assigned_by bigint REFERENCES local_users(id) ON DELETE SET NULL,
  assigned_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE patients (
  source_id bigint PRIMARY KEY,
  source_updated_at timestamptz,
  document_number varchar(64),
  medical_record_number varchar(128),
  first_name varchar(255),
  last_name varchar(255),
  birth_date date,
  sex varchar(64),
  health_insurance varchar(500),
  health_insurance_number varchar(255),
  phone varchar(255),
  email varchar(320),
  address varchar(1000),
  identity_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  local_only boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX uq_patients_document_number
  ON patients (lower(document_number)) WHERE document_number IS NOT NULL AND btrim(document_number) <> '';
CREATE UNIQUE INDEX uq_patients_medical_record_number
  ON patients (lower(medical_record_number)) WHERE medical_record_number IS NOT NULL AND btrim(medical_record_number) <> '';
CREATE INDEX idx_patients_search ON patients (lower(last_name), lower(first_name), document_number);

CREATE SEQUENCE local_patient_id_sequence START WITH 8000000000000000;

CREATE TABLE local_sessions (
  token_hash char(64) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES local_users(id) ON DELETE CASCADE,
  active_patient_id bigint REFERENCES patients(source_id) ON DELETE SET NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
