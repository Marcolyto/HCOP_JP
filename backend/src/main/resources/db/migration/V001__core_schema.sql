  continuity_status varchar(32) NOT NULL DEFAULT 'active'
    CHECK (continuity_status IN ('active','temporary_hold','discontinued')),
  effective_from_cycle smallint CHECK (effective_from_cycle BETWEEN 1 AND 500),
  suspension_reason varchar(2000),
  resume_date date,
  prescription_required boolean NOT NULL DEFAULT false,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  updated_by bigint NOT NULL REFERENCES local_users(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
