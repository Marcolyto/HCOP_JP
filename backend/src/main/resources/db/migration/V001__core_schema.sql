CREATE TABLE patient_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id bigint NOT NULL REFERENCES patients(source_id) ON DELETE CASCADE,
  category varchar(64) NOT NULL,
